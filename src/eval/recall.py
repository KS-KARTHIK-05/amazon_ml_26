"""Measure blocking recall: of S1 entities with >=1 ground-truth match, what
fraction have ALL their true matches present in the returned candidate list?
(and, more leniently, what fraction have AT LEAST ONE true match present.)

Candidates are generated by querying a sample of matched S1 entities against
the FULL candidate pool for their country (the index is built once over all
candidates, so this sample-query approach gives an unbiased recall estimate
without having to block all S1 rows).
"""

from __future__ import annotations

import sys
import time

import numpy as np
import polars as pl

from src.blocking.key_blocker import DEFAULT_MAX_POSTING, DEFAULT_TOP_K, block_country_partition
from src.data.load import load_split
from src.preprocess.normalize import normalize_address, normalize_name


def measure_recall(
    country: str,
    n_sample: int,
    k: int = DEFAULT_TOP_K,
    seed: int = 42,
    max_posting: int = DEFAULT_MAX_POSTING,
    n_jobs: int = 1,
) -> dict:
    data = load_split("train")
    gt = data["ground_truth"]

    s1_all = data["source1"].filter(pl.col("country") == country)
    s2_all = data["source2"].filter(pl.col("country") == country)
    s3_all = data["source3"].filter(pl.col("country") == country)

    matched_gt = gt.filter(pl.col("n_matches") > 0)
    s1_matched = s1_all.join(matched_gt, left_on="entity_id", right_on="source1_entity_id", how="inner")
    n = min(n_sample, s1_matched.height)
    s1_sample = s1_matched.sample(n=n, seed=seed, shuffle=True)
    print(f"country={country}: {s1_all.height} S1 total, {s1_matched.height} matched, sampling {n}")

    cand_ids = np.concatenate([s2_all["entity_id"].to_numpy(), s3_all["entity_id"].to_numpy()])
    cand_names = [normalize_name(x) for x in s2_all["business_name"]] + [
        normalize_name(x) for x in s3_all["business_name"]
    ]
    cand_addrs = [normalize_address(x) for x in s2_all["business_address"]] + [
        normalize_address(x) for x in s3_all["business_address"]
    ]

    s1_names = [normalize_name(x) for x in s1_sample["business_name"]]
    s1_addrs = [normalize_address(x) for x in s1_sample["business_address"]]

    t0 = time.time()
    result = block_country_partition(
        s1_sample["entity_id"].to_numpy(),
        s1_names,
        s1_addrs,
        cand_ids,
        cand_names,
        cand_addrs,
        k=k,
        max_posting=max_posting,
        n_jobs=n_jobs,
    )
    dt = time.time() - t0

    full_recall = partial_recall = 0
    n_true_total = n_found_total = 0
    for s1_id, true_ids in zip(s1_sample["entity_id"], s1_sample["matched_ids"]):
        true_set = set(true_ids)
        cand_set = set(result[s1_id])
        found = true_set & cand_set
        n_true_total += len(true_set)
        n_found_total += len(found)
        if found:
            partial_recall += 1
        if found == true_set:
            full_recall += 1

    out = {
        "country": country,
        "n_sample": n,
        "k": k,
        "full_recall": full_recall / n,
        "partial_recall": partial_recall / n,
        "id_level_recall": n_found_total / n_true_total if n_true_total else None,
        "seconds": dt,
    }
    print(out)
    return out


if __name__ == "__main__":
    country = sys.argv[1] if len(sys.argv) > 1 else "US"
    n_sample = int(sys.argv[2]) if len(sys.argv) > 2 else 2000
    k = int(sys.argv[3]) if len(sys.argv) > 3 else DEFAULT_TOP_K
    measure_recall(country, n_sample, k)
